class SimplifiedTest(unittest.TestCase):
    def test_word_level(self):
        cases = {
            "乾隆皇帝": "乾隆皇帝", "乾淨的衣服": "干净的衣服", "會時時刻刻想著你": "会时时刻刻想着你",
            "著名的作家": "著名的作家", "荷馬所著的伊里亞德": "荷马所著的伊里亚德", "效果顯著的": "效果显著的",
            "守衞司馬道子": "守卫司马道子", "以…而著稱": "以…而著称", "穿著深色衣服": "穿着深色衣服",
        }
        for original, simplified in cases.items():
            with self.subTest(original = original):
                self.assertEqual(to_simplified(text = original), simplified)

    def test_unchanged_entry(self):
        result = normalize_entry(original = "會時時刻刻想著你", lang = "zh")
        self.assertEqual(result, ("会时时刻刻想着你", "unchanged", "转为简体"))

    def test_fullwidth_symbols_flagged(self):
        for text, lang in [("※なお、この回は特別", "ja"), ("割引率は％で表示", "ja"), ("v′는 기호", "ko")]:
            with self.subTest(text = text):
                self.assertEqual(normalize_entry(original = text, lang = lang).status, "dropped")


class CjkRulesTest(unittest.TestCase):
    def test_counts(self):
        for lang in NORMALIZED:
            self.assertGreaterEqual(len(NORMALIZED[lang]) + len(DROPPED[lang]), 40)

    def test_normalized(self):
        for lang, cases in NORMALIZED.items():
            for original, script in cases:
                with self.subTest(lang = lang, original = original):
                    result = normalize_entry(original = original, lang = lang)
                    self.assertEqual(result.status, "normalized", msg = result.note)
                    self.assertEqual(result.script, script)

    def test_dropped(self):
        for lang, cases in DROPPED.items():
            for original, reason in cases:
                with self.subTest(lang = lang, original = original):
                    result = normalize_entry(original = original, lang = lang)
                    self.assertEqual(result.status, "dropped", msg = result.script)
                    self.assertIn(reason, result.note)

    def test_numbers_match_original(self):
        """不含单位、货币、时刻的改写，朗读稿与原文经 pipeline.compare 数词统一后一致。

        「유월 십일」「선조 이십오년(천오백구십이)」这类韩语汉字词数词后接「일」「세」等字时，比对模块会把
        它们读成别的数（十一日、二十三），属于比对模块的已知局限，列在 KNOWN 中不检查。
        """
        skip = ("单位", "货币", "时刻", "百分数")
        known = {("ko", "6월 10일"), ("ko", "1천 6백만 명이"), ("ko", "1.5배 증가"), ("ko", "6.5개의 지역적 멸종")}
        for lang, cases in NORMALIZED.items():
            for original, _ in cases:
                result = normalize_entry(original = original, lang = lang)
                if any(word in result.note for word in skip) or (lang, original) in known:
                    continue
                with self.subTest(lang = lang, original = original):
                    check = compare(script = result.script, hypothesis = clean(text = original, lang = lang), lang = lang)
                    self.assertTrue(check.match, msg = check.detail)


